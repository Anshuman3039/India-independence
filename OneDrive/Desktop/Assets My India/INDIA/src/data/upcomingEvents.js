// Helper utility to get the active upcoming festivals/events for a state based on current date
export function getUpcomingEventsForState(stateId) {
  const events = upcomingEventsData[stateId] || [];
  const todayStr = new Date().toISOString().split("T")[0]; // YYYY-MM-DD format
  
  return events.map(evt => {
    // Determine whether to use 2026 or 2027 dates
    // If the 2026 end date is in the past, use 2027.
    const date2026 = evt.dates[2026];
    const date2027 = evt.dates[2027];
    
    let activeDate = date2026;
    if (todayStr > date2026.end) {
      activeDate = date2027 || { label: "Date to be announced (TBA)" };
    }
    
    return {
      name: evt.name,
      location: evt.location,
      description: evt.description,
      dateLabel: activeDate.label
    };
  });
}
